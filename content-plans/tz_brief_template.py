def branch(phrase):
    p = phrase.lower()
    if p.startswith("чи "): return B1
    if p.startswith("як "): return B2
    if p.startswith("що таке ") or p.startswith("що означає "): return B3
    return B4

def esc(s): return s.replace('"', '""')

def formula(domain, lawyer, topic):
    q = lambda s: '"' + esc(s) + '"'
    return ("=ARRAYFORMULA(" + q(head(domain, lawyer, topic) + MID1) + "&D2:D13&" + q(MID2) + "&F2:F13&" + q(MID3)
            + "&IF(REGEXMATCH(D2:D13,\"^чи \")," + q(B1) + ",IF(REGEXMATCH(D2:D13,\"^як \")," + q(B2)
            + ",IF(REGEXMATCH(D2:D13,\"^що (таке|означає) \")," + q(B3) + "," + q(B4) + ")))&"
            + q(STY) + "&I2:I13&" + q(TAIL) + ")")

def static(domain, lawyer, topic, phrase, cluster, style):
    return head(domain, lawyer, topic) + MID1 + phrase + MID2 + cluster + MID3 + branch(phrase) + STY + style + TAIL

